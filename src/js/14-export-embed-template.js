'  function srNorm(s){ return (s||"").toLowerCase().normalize("NFD").replace(/[\\u0300-\\u036f]/g,"").replace(/[^a-z0-9]/g,""); }',
'  function srCenter(f){',
'    var minX=Infinity,minY=Infinity,maxX=-Infinity,maxY=-Infinity;',
'    function walk(c){ if (typeof c[0] === "number") { if (c[0]<minX)minX=c[0]; if (c[0]>maxX)maxX=c[0]; if (c[1]<minY)minY=c[1]; if (c[1]>maxY)maxY=c[1]; } else { c.forEach(walk); } }',
